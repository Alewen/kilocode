#pragma once

#include <fltKernel.h>

#define KG_PID_BUCKETS 256
#define KG_PID_SLOT_EMPTY 0xFFFF

////////////////////////////////////////////////////////////////////////////////
// PID 映射条目
// 表示进程 PID 与沙箱域槽位索引的映射关系
// Link     - 链表节点，挂载到哈希桶链表
// Pid      - 进程 PID
// SlotIndex - 沙箱域在 gState->Domain[] 数组中的槽位索引
////////////////////////////////////////////////////////////////////////////////
typedef struct _KG_PID_ENTRY {
    LIST_ENTRY Link;      // 链表节点，挂载到哈希桶链表
    HANDLE Pid;           // 进程 PID
    ULONG SlotIndex;      // 沙箱域在 gState->Domain[] 数组中的槽位索引
} KG_PID_ENTRY;

////////////////////////////////////////////////////////////////////////////////
// PID 映射表（无锁读并发结构）
// 使用哈希桶 + 分离链表存储 PID→槽位映射
// RundownRef  - 用于 RCU 风格的无锁读取保护
// Buckets     - 256 个哈希桶，每个桶一个双向链表
////////////////////////////////////////////////////////////////////////////////
typedef struct _KG_PID_MAP {
    EX_RUNDOWN_REF RundownRef;          // RCU 风格无锁读取保护，等待所有读者释放后安全释放
    LIST_ENTRY Buckets[KG_PID_BUCKETS]; // 256 个哈希桶，每个桶一个双向链表（KG_PID_ENTRY）
} KG_PID_MAP;

extern USHORT gPidSlotFast[65536];

////////////////////////////////////////////////////////////////////////////////
// 全局唯一，任意一个沙箱内进程发生变更，数量就 +1
////////////////////////////////////////////////////////////////////////////////
extern volatile LONG gPidMapEpoch;

////////////////////////////////////////////////////////////////////////////////
// 功能：分配并初始化一个 PID 映射表，包含哈希桶和 Rundown 保护
// 参数：无
// 返回值：新分配的 PID 映射表指针；失败返回 NULL
////////////////////////////////////////////////////////////////////////////////
KG_PID_MAP* KgAllocPidMap(VOID);

////////////////////////////////////////////////////////////////////////////////
// 功能：释放 PID 映射表及其所有条目的内存
//       遍历每个哈希桶链表，逐条释放 KG_PID_ENTRY
// 参数：
//   map - 要释放的 PID 映射表指针；允许 NULL
// 返回值：无
////////////////////////////////////////////////////////////////////////////////
VOID KgFreePidMap(KG_PID_MAP* map);
////////////////////////////////////////////////////////////////////////////////
// 功能：在 PID 映射表中查找指定进程所属的沙箱域槽位索引
//       遍历对应哈希桶的链表进行精确匹配
// 参数：
//   map - PID 映射表指针
//   pid - 目标进程 PID
// 返回值：沙箱域槽位索引；若未找到返回 (ULONG)-1
////////////////////////////////////////////////////////////////////////////////
ULONG KgLookupSlotByPid(KG_PID_MAP* map, HANDLE pid);

////////////////////////////////////////////////////////////////////////////////
// 功能：通过快速缓存 gPidSlotFast 检查指定进程是否在沙箱内
//       仅通过位号索引查表，性能远高于链表遍历
// 参数：
//   pid - 目标进程 PID
// 返回值：沙箱域槽位索引（0 基）；若不在沙箱内返回 (ULONG)-1
////////////////////////////////////////////////////////////////////////////////
ULONG KgIsPidInSandBox(HANDLE pid);
////////////////////////////////////////////////////////////////////////////////
// 功能：设置指定进程的沙箱域槽位索引
//       如果 PID 已存在则更新槽位，否则新建条目插入
//       同时更新快速缓存 gPidSlotFast
// 参数：
//   map       - PID 映射表指针
//   pid       - 目标进程 PID
//   slotIndex - 沙箱域槽位索引
// 返回值：STATUS_SUCCESS 成功，STATUS_INSUFFICIENT_RESOURCES 内存不足
////////////////////////////////////////////////////////////////////////////////
NTSTATUS KgSetPidSlot(KG_PID_MAP* map, HANDLE pid, ULONG slotIndex);

////////////////////////////////////////////////////////////////////////////////
// 功能：从 PID 映射表中移除指定进程条目并释放对应内存
//       同时清除快速缓存 gPidSlotFast 中对应槽位
// 参数：
//   map - PID 映射表指针
//   pid - 要移除的目标进程 PID
// 返回值：无
////////////////////////////////////////////////////////////////////////////////
VOID KgRemovePid(KG_PID_MAP* map, HANDLE pid);

////////////////////////////////////////////////////////////////////////////////
// 功能：克隆整个 PID 映射表，创建一份独立的深拷贝
//       用于在进程继承/进程退出时基于当前 PidMap 创建新副本
// 参数：
//   src - 源 PID 映射表指针；若为 NULL 则返回空的新映射表
// 返回值：新分配的 PID 映射表指针，失败返回 NULL
////////////////////////////////////////////////////////////////////////////////
KG_PID_MAP* KgClonePidMap(KG_PID_MAP* src);
////////////////////////////////////////////////////////////////////////////////
// 功能：原子替换全局 PID 映射表指针，返回旧映射表指针
//       通过 InterlockedExchangePointer 实现无锁切换
// 参数：
//   newMap - 要替换的新映射表指针
// 返回值：旧的映射表指针，供后续延迟释放
////////////////////////////////////////////////////////////////////////////////
KG_PID_MAP* KgSwapPidMap(KG_PID_MAP* newMap);

////////////////////////////////////////////////////////////////////////////////
// 功能：等待旧映射表的 Rundown 保护释放后，安全释放映射表内存
//       与 KgSwapPidMap 配合使用，确保正在访问旧映射表的线程已完成
// 参数：
//   old - 旧的映射表指针；允许 NULL
// 返回值：无
////////////////////////////////////////////////////////////////////////////////
VOID KgFreeOldPidMap(KG_PID_MAP* old);

////////////////////////////////////////////////////////////////////////////////
// 功能：初始化全局快速 PID 查找表 gPidSlotFast，将所有槽位标记为空
//       在驱动入口 DriverEntry 阶段调用一次
// 参数：无
// 返回值：无
////////////////////////////////////////////////////////////////////////////////
VOID KgPidMapInit(VOID);
