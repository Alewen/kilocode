// 参数：
//   Pid - 要移除的进程 PID
// 返回值：无
////////////////////////////////////////////////////////////////////////////////
VOID KgRemoveTrustedPid(HANDLE Pid);

////////////////////////////////////////////////////////////////////////////////
// 功能：向用户态 bwrap 推送进程创建/退出事件
// 参数：
//   slotIndex - 沙箱域槽位索引
//   pid       - 进程 PID
//   msgType   - KG_PORT_MSG_PROCESS_CREATE 或 KG_PORT_MSG_PROCESS_EXIT
//   imageName - 进程映像名称（可选）
// 返回值：无
////////////////////////////////////////////////////////////////////////////////
VOID KgSendProcessEvent(ULONG slotIndex, ULONG pid, ULONG msgType, PUNICODE_STRING imageName);
