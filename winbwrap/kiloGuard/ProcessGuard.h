#pragma once

#include <fltKernel.h>

extern PVOID gObRegistration;

////////////////////////////////////////////////////////////////////////////////
// 功能：注册进程/线程/映像加载通知回调和对象回调
//       包括进程创建退出通知(PstSetCreateProcessNotifyRoutineEx)、
//       线程创建通知、映像加载通知、进程句柄操作回调(ObRegisterCallbacks)
// 参数：无
// 返回值：STATUS_SUCCESS 表示所有回调注册成功，否则返回相应错误码
////////////////////////////////////////////////////////////////////////////////
NTSTATUS KgRegisterProcessCallbacks(VOID);

////////////////////////////////////////////////////////////////////////////////
// 功能：注销所有已注册的进程/线程/映像加载通知回调和对象回调
//       与 KgRegisterProcessCallbacks 成对使用，在驱动卸载时调用
// 参数：无
// 返回值：无
////////////////////////////////////////////////////////////////////////////////
VOID KgUnregisterProcessCallbacks(VOID);
